"""JPEG-quality confound analysis: is ELA separability just compression quality?"""

import argparse
import os
from pathlib import Path

import numpy as np
from scipy.stats import mannwhitneyu
from sklearn.metrics import f1_score

from data.ela import read_jpeg_quality

BIN_WIDTH = 10


def mann_whitney(a, b) -> dict:
    """Two-sided Mann-Whitney U on quality factors; None values are dropped, not coerced."""
    a = [x for x in a if x is not None]
    b = [x for x in b if x is not None]
    r = {
        "n_a": len(a),
        "n_b": len(b),
        "median_a": float(np.median(a)) if a else None,
        "median_b": float(np.median(b)) if b else None,
        "p_value": None,
    }
    if a and b:
        r["p_value"] = float(mannwhitneyu(a, b, alternative="two-sided").pvalue)
    return r


def stratified_f1(y_true, y_pred, qf, min_per_class: int = 20) -> dict:
    """Macro-F1 per 10-wide quality bin [lo, hi); bins without both classes are never scored."""
    y_true = np.asarray(y_true).astype(int)
    y_pred = np.asarray(y_pred).astype(int)

    groups = {}
    for yt, yp, q in zip(y_true, y_pred, qf):
        if q is None:
            continue
        lo = int(q) // BIN_WIDTH * BIN_WIDTH
        groups.setdefault(lo, []).append((yt, yp))

    bins = []
    for lo in sorted(groups):
        items = groups[lo]
        yt = np.array([t for t, _ in items])
        yp = np.array([p for _, p in items])
        n_ok = int((yt == 0).sum())
        n_tampered = int((yt == 1).sum())
        scored = n_ok >= min_per_class and n_tampered >= min_per_class
        bins.append({
            "lo": lo,
            "hi": lo + BIN_WIDTH,
            "n_ok": n_ok,
            "n_tampered": n_tampered,
            "f1": float(f1_score(yt, yp, average="macro", zero_division=0)) if scored else None,
        })

    usable = [b["f1"] for b in bins if b["f1"] is not None]
    return {
        "bins": bins,
        "usable_bins": len(usable),
        "insufficient_bins": len(bins) - len(usable),
        "macro_f1": float(np.mean(usable)) if usable else None,
    }


def _resolve(path: str, data_dir: str) -> str:
    return path if os.path.exists(path) else os.path.join(data_dir, path)


def analyse_run(npz_path: str, data_dir: str = "data", threshold: float = 0.5,
                min_per_class: int = 20) -> dict:
    """Read one evaluate.py prediction artefact and return its confound statistics."""
    d = np.load(npz_path)
    paths = [str(p) for p in d["paths"]]
    labels = np.asarray(d["labels"]).astype(int)
    probs = np.asarray(d["probs"]).astype(float)
    preds = (probs >= threshold).astype(int)
    qf = [read_jpeg_quality(_resolve(p, data_dir)) for p in paths]

    mw = mann_whitney(
        [q for q, y in zip(qf, labels) if y == 0],
        [q for q, y in zip(qf, labels) if y == 1],
    )
    return {
        "name": Path(npz_path).stem,
        "n": len(labels),
        "n_no_quality": sum(q is None for q in qf),
        "mw": mw,
        "strat": stratified_f1(labels, preds, qf, min_per_class=min_per_class),
    }


def _fmt(x, spec: str = ".3g") -> str:
    return "n/a" if x is None else format(x, spec)


def render_markdown(results, threshold: float = 0.5, min_per_class: int = 20) -> str:
    lines = [
        "# JPEG-quality confound analysis",
        "",
        "Generated by `python -m analysis.confound`.",
        f"Decision threshold: {threshold:.2f}. Per-bin macro-F1 is scored only where both "
        f"classes have at least {min_per_class} images; other bins are reported as "
        "insufficient and contribute nothing to the average.",
        "Quality factors are read from the JPEG quantization tables; images without one "
        "(BMP/TIFF or unreadable) are excluded from both tests, never coerced to 0.",
        "",
    ]
    for r in results:
        mw, st = r["mw"], r["strat"]
        lines += [
            f"## {r['name']}",
            "",
            f"Images analysed: {r['n']}. No readable JPEG quality factor: {r['n_no_quality']}.",
            "",
            f"Mann-Whitney U (authentic vs tampered quality): "
            f"n authentic={mw['n_a']}, n tampered={mw['n_b']}, "
            f"median authentic={_fmt(mw['median_a'])}, "
            f"median tampered={_fmt(mw['median_b'])}, "
            f"p={_fmt(mw['p_value'])}.",
            "",
            "| Quality bin | n authentic | n tampered | Macro-F1 | Status |",
            "|---|---:|---:|---:|---|",
        ]
        for b in st["bins"]:
            status = ("scored" if b["f1"] is not None
                      else f"insufficient (needs {min_per_class} per class)")
            lines.append(f"| {b['lo']}-{b['hi'] - 1} | {b['n_ok']} | {b['n_tampered']} "
                         f"| {_fmt(b['f1'], '.4f')} | {status} |")
        if st["macro_f1"] is None:
            lines.append(f"| _none_ | | | n/a | {st['insufficient_bins']} insufficient bins |")
        lines += [
            "",
            f"Macro-F1 across {st['usable_bins']} usable bins: "
            f"{_fmt(st['macro_f1'], '.4f')}.",
            "",
        ]
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser(
        description="JPEG-quality confound analysis over evaluate.py prediction artefacts")
    p.add_argument("--data-dir", default="data",
                   help="Prefix for image paths that are not reachable as stored")
    p.add_argument("--predictions", nargs="+", required=True,
                   help="One or more predictions/{run}_{split}.npz files")
    p.add_argument("--out", default="docs/results/confound.md")
    p.add_argument("--threshold", type=float, default=0.5,
                   help="Probability cut for y_pred (default: 0.5, the F1-argmax cut)")
    p.add_argument("--min-per-class", type=int, default=20)
    args = p.parse_args()

    results = [analyse_run(f, args.data_dir, args.threshold, args.min_per_class)
               for f in args.predictions]

    for r in results:
        st = r["strat"]
        print(f"\n{r['name']}")
        print(f"  images={r['n']}  no_quality={r['n_no_quality']}  "
              f"usable_bins={st['usable_bins']}  insufficient_bins={st['insufficient_bins']}")
        for b in st["bins"]:
            f1 = "insufficient" if b["f1"] is None else f"{b['f1']:.4f}"
            print(f"  [{b['lo']:>3}-{b['hi'] - 1:>3}] authentic={b['n_ok']:>4} "
                  f"tampered={b['n_tampered']:>4}  f1={f1}")

    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w") as f:
        f.write(render_markdown(results, args.threshold, args.min_per_class))
    print(f"\nWritten to {args.out}")


if __name__ == "__main__":
    main()
